from __future__ import annotations

from typing import Any, Literal

import yaml
from pydantic import BaseModel, Field

from spack_ai.schemas import EnvironmentSpec, SkillResult
from spack_ai.skills import register
from spack_ai.skills.base import Skill, SkillContext, SkillError
from spack_ai.skills.recipe.render import repo_root


class External(BaseModel):
    spec: str = Field(description="Spec of the system install, e.g. 'openmpi@4.1.6'.")
    prefix: str | None = Field(default=None, description="Install prefix on the machine.")
    modules: list[str] = Field(default_factory=list, description="Modules that load it instead.")
    buildable: bool = Field(default=False, description="Allow Spack to build it anyway.")


class EnvironmentInput(BaseModel):
    specs: list[str] = Field(
        default_factory=list,
        description="Root specs. Defaults to the package recipe written in this session.",
    )
    name: str = Field(default="default", description="Environment directory under envs/.")
    view: bool = True
    unify: bool | Literal["when_possible"] = True
    include_local_repo: bool = Field(
        default=True, description="Add this session's generated package repository."
    )
    externals: list[External] = Field(
        default_factory=list, description="System-installed packages (MPI, CUDA, compilers)."
    )
    requirements: dict[str, str] = Field(
        default_factory=dict,
        description="Package or virtual -> required spec, e.g. {'mpi': 'cray-mpich'}.",
    )
    packages: dict[str, Any] = Field(
        default_factory=dict, description="Extra raw packages: configuration merged last."
    )
    build_jobs: int | None = None
    mirrors: dict[str, str] = Field(default_factory=dict)


def render_environment(env: EnvironmentSpec) -> str:
    body: dict[str, Any] = {"specs": env.specs, "view": env.view,
                            "concretizer": {"unify": env.unify}}
    if env.repos:
        body["repos"] = env.repos
    if env.packages:
        body["packages"] = env.packages
    if env.config:
        body["config"] = env.config
    if env.mirrors:
        body["mirrors"] = env.mirrors
    if env.modules:
        body["modules"] = env.modules
    header = "# Generated by spack-ai. Activate with: spack env activate -d <this directory>\n"
    return header + yaml.safe_dump({"spack": body}, sort_keys=False, default_flow_style=False)


def build_environment(ctx: SkillContext, params: EnvironmentInput) -> EnvironmentSpec:
    specs = params.specs or ([ctx.state["recipe_name"]] if ctx.state.get("recipe_name") else [])
    if not specs:
        raise SkillError("No specs given and no recipe written yet.")
    packages: dict[str, Any] = {}
    for ext in params.externals:
        name = ext.spec.split("@")[0].split("+")[0].split("~")[0]
        entry: dict[str, Any] = {"spec": ext.spec}
        if ext.prefix:
            entry["prefix"] = ext.prefix
        if ext.modules:
            entry["modules"] = ext.modules
        pkg = packages.setdefault(name, {"externals": []})
        pkg["externals"].append(entry)
        if not ext.buildable:
            pkg["buildable"] = False
    for name, requirement in params.requirements.items():
        packages.setdefault(name, {})["require"] = [requirement]
    for name, value in params.packages.items():
        packages[name] = {**packages.get(name, {}), **value}

    repos = []
    if params.include_local_repo and ctx.state.get("recipe_path"):
        settings = ctx.settings
        repos.append(str(repo_root(ctx.workspace, settings.recipe.namespace, settings.spack.is_v1)))
    return EnvironmentSpec(
        specs=specs,
        view=params.view,
        unify=params.unify,
        repos=repos,
        packages=packages,
        config={"build_jobs": params.build_jobs} if params.build_jobs else {},
        mirrors=params.mirrors,
    )


@register
class GenerateEnvironment(Skill):
    name = "generate_environment"
    category = "generation"
    description = (
        "Write a Spack environment (spack.yaml) with root specs, the session's local package "
        "repository, system externals (MPI, CUDA, compilers), provider requirements, and "
        "build settings."
    )
    Input = EnvironmentInput
    knowledge_sections = ("environments", "hpc_sites")

    def run(self, params: EnvironmentInput) -> SkillResult:
        env = build_environment(self.ctx, params)
        path = self.ctx.resolve_output(f"envs/{params.name}/spack.yaml")
        text = render_environment(env)
        path.write_text(text)
        self.ctx.state["env_dir"] = str(path.parent)
        return SkillResult(
            summary=f"Wrote {self.ctx.relative(path)} with specs: {', '.join(env.specs)}.",
            data={"path": str(path), "spack.yaml": text},
            files=[str(path)],
        )
